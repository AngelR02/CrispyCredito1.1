import assert from 'node:assert/strict';
import { installment,schedule,ledger,addMonths,nextDue } from '../dist/finance.mjs';
const l={id:'l',principal:1000000,rate:1.5,months:6,start:'2026-01-31'};
const s=schedule(l);
assert.equal(s.at(-1).balance,0);
assert.equal(s.reduce((a,r)=>a+r.capital,0),l.principal);
assert.equal(s[0].interest,15000);
assert.equal(s[0].date,'2026-02-28');
assert.equal(s[1].date,'2026-03-31');
assert.equal(addMonths('2024-01-31',1),'2024-02-29');
const free=schedule({...l,rate:0,months:3});
assert.deepEqual(free.map(r=>r.total),[333333,333333,333334]);
assert.equal(installment(1000000,0,4),250000);
const p=[{loanId:'l',capital:200000,interest:15000,date:'2026-02-28',createdAt:'2026-02-28T12:00:00Z'}];
assert.equal(ledger(l,p).balance,800000);
assert.equal(ledger(l,p).paidInterest,15000);
assert.equal(ledger(l,[{...p[0],capital:0}]).balance,1000000);
assert.equal(ledger(l,[{...p[0],reversed:true}]).balance,1000000);
assert.equal(nextDue(l,[{...p[0],capital:1000000}]),null);
assert.throws(()=>installment(1000,1.5,0));
assert.throws(()=>installment(1000,-1,6));
assert.throws(()=>installment(NaN,1,6));
console.log('Finance checks passed: schedule totals, dates, zero interest, ledger splits and reversals.');
